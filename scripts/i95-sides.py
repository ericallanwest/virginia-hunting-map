"""Write src/regs/i95.generated.ts: jurisdictions entirely west of I-95.

Jurisdictions that I-95 crosses are split into 'w95'/'e95' pieces by
scripts/split-jurisdictions.py; this lists the ones wholly on the west side
(grouse season is open only west of I-95). Run from scripts/build-geo.sh.
"""
import importlib.util
import json
from pathlib import Path

from shapely.geometry import shape

ROOT = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("sj", ROOT / "scripts/split-jurisdictions.py")
sj = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sj)

line = sj.north_to_south(sj.i95())
feats = json.load(open(ROOT / "public/data/jurisdictions.geojson"))["features"]
crossing = set(sj.I95_JURISDICTIONS)
west = {"county": [], "city": []}
for f in feats:
    jid = f["properties"]["id"]
    if jid in crossing or jid in [w for v in west.values() for w in v]:
        continue
    if sj.side(line, shape(f["geometry"])) == "west":
        typ, name = jid.split(":")
        if name not in west[typ]:
            west[typ].append(name)

out = ROOT / "src/regs/i95.generated.ts"
out.write_text(
    "// Generated by scripts/i95-sides.py — do not edit.\n"
    "// Counties and cities entirely west of I-95. Jurisdictions I-95 crosses are split into\n"
    "// 'w95'/'e95' pieces in the map data and listed here with the '/w95' suffix.\n"
    f"export const WEST_OF_I95_COUNTIES = {json.dumps(sorted(west['county']) + sorted(j.split(':')[1] + '/w95' for j in crossing if j.startswith('county:')))};\n"
    f"export const WEST_OF_I95_CITIES = {json.dumps(sorted(west['city']) + sorted(j.split(':')[1] + '/w95' for j in crossing if j.startswith('city:')))};\n",
    encoding="utf-8",
)
print(out, len(west["county"]), "counties and", len(west["city"]), "cities wholly west")
